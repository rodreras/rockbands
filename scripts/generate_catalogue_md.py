"""Regenerate CATALOGUE.md from the catalogue, so the docs can never drift from the code.

    python scripts/generate_catalogue_md.py > CATALOGUE.md
"""

from rockbands import SENSORS, translate
from rockbands.errors import BandNotAvailableError
from rockbands.ratios import CATALOGUE, supported_sensors

SHOW = ("s2", "l8", "l7")


def native(item, key):
    try:
        out = translate(item, key)
    except BandNotAvailableError:
        return "-"
    return ", ".join(out) if isinstance(out, tuple) else out


def main() -> None:
    print("# Catalogue\n")
    print("Generated by `scripts/generate_catalogue_md.py`. `Runs on` lists every sensor whose bands "
          "allow the formula; the native columns show the formula rewritten in that sensor's band ids "
          "(`-` = the sensor lacks a band it needs).\n")
    groups = [
        ("Ratios on standard bands (multi-sensor)", lambda i: i.kind == "ratio" and i.namespace == "standard"),
        ("RGB composites (channels R, G, B)", lambda i: i.kind == "composite"),
        ("ASTER ratios (ASTER band numbers, ASTER only)", lambda i: i.namespace == "aster"),
    ]
    for title, pick in groups:
        print(f"## {title}\n")
        aster_only = title.startswith("ASTER")
        head = ["Function", "Formula", "Runs on"] if aster_only else ["Function", "Formula", "Runs on", *SHOW]
        print("| " + " | ".join(head) + " |")
        print("| " + " | ".join("---" for _ in head) + " |")
        for item in filter(pick, CATALOGUE.values()):
            cells = [f"`{item.name}`", f"`{item.formula}`", ", ".join(supported_sensors(item))]
            if not aster_only:
                cells += [f"`{native(item, k)}`" if native(item, k) != "-" else "-" for k in SHOW]
            print("| " + " | ".join(cells) + " |")
        print()
    print("## Sensors\n")
    print("| Key | Name | Standard roles available |")
    print("| --- | --- | --- |")
    for s in SENSORS.values():
        print(f"| `{s.key}` | {s.name} | {', '.join(s.standards)} |")


if __name__ == "__main__":
    main()
